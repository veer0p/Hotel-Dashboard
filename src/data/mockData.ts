// Helper functions
export const getGuestById = (id: string): Guest | undefined => mockGuests.find(g => g.id === id);
export const getRoomById = (id: string): Room | undefined => mockRooms.find(r => r.id === id);
export const getBookingById = (id: string): Booking | undefined => mockBookings.find(b => b.id === id);
export const getDecorationPackageById = (id: string): DecorationPackage | undefined => mockDecorationPackages.find(d => d.id === id);

export const getBookingWithDetails = (booking: Booking) => {
  const guest = getGuestById(booking.guestId);
  const room = getRoomById(booking.roomId);
  const decoration = booking.decorationPackageId ? getDecorationPackageById(booking.decorationPackageId) : undefined;
  return { ...booking, guest, room, decoration };
};
